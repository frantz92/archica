// Writes out/.htaccess (Apache / LiteSpeed) after `next build`: HTTPS and host redirects, the
// home redirect, security headers, caching, compression and the 404 page.
// Run automatically by `npm run build` (postbuild).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  FORCED_TYPES,
  HOME_PATH,
  HTML_CACHE,
  SITE_ORIGIN,
  securityHeaders,
} from './lib/site-config.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const host = new URL(SITE_ORIGIN).host;
const escapeQuotes = (value) => value.replaceAll('"', '\\"');

const headerLines = securityHeaders({ preview: process.env.SITE_ENV === 'preview' })
  .map(([name, value]) => `  Header always set ${name} "${escapeQuotes(value)}"`)
  .join('\n');

const forcedTypes = Object.entries(FORCED_TYPES)
  .map(([name, type]) => `<Files "${name}">\n  ForceType ${type}\n</Files>`)
  .join('\n');

const htaccess = `# Generated by scripts/build-htaccess.mjs - do not edit by hand.
Options -Indexes
DirectorySlash On
DirectoryIndex index.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # HTTPS on whatever host answers (also behind a proxy that sets X-Forwarded-Proto). The host is
  # not forced to archica.pl here, so the same files work on the host's test address.
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]

  # www.archica.pl -> archica.pl
  RewriteCond %{HTTP_HOST} ^www\\.${host.replaceAll('.', '\\.')}$ [NC]
  RewriteRule ^ ${SITE_ORIGIN}%{REQUEST_URI} [R=301,L]

  # The site starts in the default language.
  RewriteRule ^$ ${HOME_PATH} [R=301,L]
</IfModule>

ErrorDocument 404 /404.html

<IfModule mod_headers.c>
${headerLines}

  # HTML is revalidated on every visit; hashed assets never change.
  <FilesMatch "\\.html$">
    Header set Cache-Control "${HTML_CACHE}"
  </FilesMatch>
  <FilesMatch "\\.(js|css|woff2)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(webp|png|jpg|svg|ico|webmanifest)$">
    Header set Cache-Control "public, max-age=2592000"
  </FilesMatch>
</IfModule>

${forcedTypes}

AddType application/manifest+json .webmanifest

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript text/javascript application/json image/svg+xml application/manifest+json text/xml application/xml text/plain
</IfModule>
`;

writeFileSync(join(root, 'out', '.htaccess'), htaccess);
console.log('out/.htaccess written');
